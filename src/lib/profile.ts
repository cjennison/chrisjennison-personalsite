/**
 * Structural profile data: identifiers, dates, links, and ordering.
 * All display text lives in messages/{locale}.json under the "Profile" namespace,
 * keyed by the ids defined here.
 */

export type YearMonth = `${number}-${number}${number}`;

export type EmploymentType = "fullTime" | "contract" | "partTime";

export interface Role {
  /** Key under Profile.roles in the message files */
  id: string;
  start: YearMonth;
  /** null means the role is current */
  end: YearMonth | null;
  type: EmploymentType;
}

export interface Company {
  id: string;
  name: string;
  url?: string;
  roles: readonly Role[];
}

export type MetricKind = "change" | "value";

export interface ImpactItem {
  /** Key under Profile.impact in the message files */
  id: string;
  metrics: readonly { id: string; kind: MetricKind }[];
}

export interface EducationItem {
  /** Key under Profile.education in the message files */
  id: string;
  school: string;
  startYear: number;
  endYear: number;
}

