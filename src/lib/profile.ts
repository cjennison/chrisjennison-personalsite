/** Converts "2024-09" to a mid-month UTC date so formatting never shifts months */
export function yearMonthToDate(value: YearMonth): Date {
  const [year, month] = value.split("-").map(Number);
  return new Date(Date.UTC(year ?? 0, (month ?? 1) - 1, 15));
}

export function getAgeInYears(birthDateIso: string, now = new Date()): number {
  const birth = new Date(`${birthDateIso}T00:00:00Z`);
  let age = now.getUTCFullYear() - birth.getUTCFullYear();
  const beforeBirthday =
    now.getUTCMonth() < birth.getUTCMonth() ||
    (now.getUTCMonth() === birth.getUTCMonth() &&
      now.getUTCDate() < birth.getUTCDate());
  if (beforeBirthday) age -= 1;
  return age;
}
